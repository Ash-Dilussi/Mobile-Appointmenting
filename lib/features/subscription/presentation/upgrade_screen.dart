import '../../../core/theme/app_spacing.dart';
import '../../../core/entitlements/app_feature.dart';
import '../../../core/entitlements/entitlement_provider.dart';
import '../../../core/entitlements/plan_tier.dart';
import '../../../core/logging/logger_service.dart';
import '../../../features/auth/presentation/providers/auth_session_provider.dart';

// ── Checkout URL constants (replace with your actual Stripe/Paddle links) ─────
// These are the hosted payment page URLs generated by Stripe/Paddle.
// Append ?client_reference_id={institutionId} to associate the payment.
// IMPORTANT: store these in remote config or environment, not hard-coded here.
class _CheckoutUrls {
  static const pro = 'https://buy.stripe.com/YOUR_PRO_LINK';
  static const enterprise = 'https://buy.stripe.com/YOUR_ENTERPRISE_LINK';
  // Paddle alternative: 'https://YOUR_VENDOR.paddle.com/checkout/product/XXX'
}

// ─────────────────────────────────────────────────────────────────────────────

class UpgradeScreen extends ConsumerStatefulWidget {
  /// [triggerFeature] is the feature that prompted this screen (from route extra).
  const UpgradeScreen({super.key, this.triggerFeature});
  final AppFeature? triggerFeature;

  @override
  ConsumerState<UpgradeScreen> createState() => _UpgradeScreenState();
}

class _UpgradeScreenState extends ConsumerState<UpgradeScreen> {
  bool _isRefreshing = false;

  // ── Pull-to-refresh: re-check entitlements after user returns from browser ──
  Future<void> _refresh() async {
    setState(() => _isRefreshing = true);
    try {
      final session = ref.read(authSessionProvider);
      if (session?.institutionId != null) {
        await ref
            .read(entitlementProvider.notifier)
            .refresh(institutionId: session!.institutionId!);
      }
    } catch (e) {
      LoggerService.instance.log(
        LogLevel.warning,
        'UpgradeScreen',
        'Refresh failed: $e',
      );
    } finally {
      if (mounted) setState(() => _isRefreshing = false);
    }
  }

  Future<void> _launchCheckout(PlanTier tier, String institutionId) async {
    final baseUrl =
        tier == PlanTier.pro ? _CheckoutUrls.pro : _CheckoutUrls.enterprise;

    // Append institution ID so webhook can find the right Firestore document.
    final url = Uri.parse('$baseUrl?client_reference_id=$institutionId');

    LoggerService.instance.log(
      LogLevel.info,
      'UpgradeScreen',
      'Launching checkout for ${tier.displayName}',
    );

    if (await canLaunchUrl(url)) {
      await launchUrl(url, mode: LaunchMode.externalApplication);
    } else {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('Could not open checkout page.')),
        );
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    final currentTier = ref.watch(currentTierProvider);
    final institutionId = ref.read(authSessionProvider)?.institutionId ?? '';

    return Scaffold(
      backgroundColor: AppColors.surface,
      appBar: AppBar(
        title: const Text('Choose Your Plan'),
        centerTitle: true,
        actions: [
          if (_isRefreshing)
            const Padding(
              padding: EdgeInsets.all(16),
              child: SizedBox(
                  width: 20,
                  height: 20,
                  child: CircularProgressIndicator(strokeWidth: 2)),
            )
          else
            IconButton(
              icon: const Icon(Icons.refresh),
              tooltip: 'Already paid? Refresh',
              onPressed: _refresh,
            ),
        ],
      ),
      body: RefreshIndicator(
        onRefresh: _refresh,
        child: ListView(
          padding: const EdgeInsets.all(AppSpacing.screenPadding),
          children: [
            if (widget.triggerFeature != null) ...[
              _FeatureHighlightBanner(feature: widget.triggerFeature!),
              const SizedBox(height: AppSpacing.xl),
            ],
            _PlanCard(
              tier: PlanTier.pro,
              isCurrent: currentTier == PlanTier.pro,
              isHighlighted: true,
              triggerFeature: widget.triggerFeature,
              onSubscribe: () => _launchCheckout(PlanTier.pro, institutionId),
            ),
            const SizedBox(height: AppSpacing.lg),
            _PlanCard(
              tier: PlanTier.enterprise,
              isCurrent: currentTier == PlanTier.enterprise,
              triggerFeature: widget.triggerFeature,
              onSubscribe: () =>
                  _launchCheckout(PlanTier.enterprise, institutionId),
            ),
            const SizedBox(height: AppSpacing.xxl),
            _FeatureComparisonTable(currentTier: currentTier),
            const SizedBox(height: AppSpacing.xl),
            Text(
              'Subscriptions renew automatically. Cancel anytime from your '
              'billing portal. All prices exclude applicable taxes.',
              textAlign: TextAlign.center,
              style: TextStyle(
                fontSize: 12,
                color: AppColors.secondary.withValues(alpha: 0.7),
                height: 1.5,
              ),
            ),
            const SizedBox(height: AppSpacing.xxl),
          ],
        ),
      ),
    );
  }
}

class _FeatureHighlightBanner extends StatelessWidget {
  const _FeatureHighlightBanner({required this.feature});
  final AppFeature feature;

  @override
  Widget build(BuildContext context) {
    return Container(
      padding: const EdgeInsets.all(AppSpacing.md),
