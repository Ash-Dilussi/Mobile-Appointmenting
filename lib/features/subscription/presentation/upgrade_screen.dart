// Full paywall screen. Reached from:
//   - UpgradeBottomSheet CTA ("Upgrade to Pro")
//   - Settings → Plan & Billing
//
// Route: /upgrade (optionally with extra: {'triggerFeature': 'callRecording'})
//
// On "Subscribe" tap, opens the Stripe/Paddle checkout URL in the browser.
// After payment, the Stripe/Paddle webhook hits your backend Cloud Function,
// which writes to Firestore. The app re-bootstraps on next launch or background
// resume. For an immediate in-session reflect, the user can pull-to-refresh
// on this screen (calls entitlementProvider.notifier.refresh()).

