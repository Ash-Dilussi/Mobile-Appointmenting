    );
  }
}

class _PlanCard extends StatelessWidget {
  const _PlanCard({
    required this.tier,
    required this.isCurrent,
    required this.onSubscribe,
    this.isHighlighted = false,
    this.triggerFeature,
  });

  final PlanTier tier;
  final bool isCurrent;
  final bool isHighlighted;
  final AppFeature? triggerFeature;
  final VoidCallback onSubscribe;

  String get _priceLabel {
    switch (tier) {
      case PlanTier.pro:
        return '\$29 / month';
      case PlanTier.enterprise:
        return '\$99 / month';
      default:
        return 'Free';
    }
  }

  @override
  Widget build(BuildContext context) {
    return Container(
      decoration: BoxDecoration(
        color: AppColors.surface,
        borderRadius: BorderRadius.circular(AppSpacing.radiusLg),
        border: Border.all(
          color: isHighlighted
              ? AppColors.primary
              : AppColors.secondary.withValues(alpha: 0.2),
          width: isHighlighted ? 2 : 1,
        ),
        boxShadow: isHighlighted
            ? [
                BoxShadow(
                  color: AppColors.primary.withValues(alpha: 0.12),
                  blurRadius: 16,
                  offset: const Offset(0, 4),
                )
              ]
            : null,
      ),
      child: Padding(
        padding: const EdgeInsets.all(AppSpacing.lg),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                Text(tier.displayName,
                    style: const TextStyle(
                        fontSize: 20, fontWeight: FontWeight.w700)),
                if (isHighlighted) ...[
                  const SizedBox(width: AppSpacing.sm),
                  Container(
                    padding:
                        const EdgeInsets.symmetric(horizontal: 8, vertical: 2),
                    decoration: BoxDecoration(
                      color: AppColors.primary,
                      borderRadius: BorderRadius.circular(999),
                    ),
                    child: const Text('Popular',
                        style: TextStyle(
                            color: Colors.white,
                            fontSize: 11,
                            fontWeight: FontWeight.w700)),
                  ),
                ],
                const Spacer(),
                Text(_priceLabel,
                    style: TextStyle(
                        fontSize: 16,
                        fontWeight: FontWeight.w600,
                        color: AppColors.primary)),
              ],
            ),
            const SizedBox(height: AppSpacing.md),
            ...tier.allowedFeatures
                .where((f) => !PlanTier.free.includes(f))
                .map((f) => _FeatureRow(
                      feature: f,
                      isHighlighted: f == triggerFeature,
                    )),
            const SizedBox(height: AppSpacing.lg),
            SizedBox(
              width: double.infinity,
              child: isCurrent
                  ? OutlinedButton(
                      onPressed: null, child: const Text('Current Plan'))
                  : FilledButton(
                      onPressed: onSubscribe,
                      child: Text('Subscribe to ${tier.displayName}'),
                    ),
            ),
          ],
        ),
      ),
    );
  }
}

class _FeatureRow extends StatelessWidget {
  const _FeatureRow({required this.feature, this.isHighlighted = false});
  final AppFeature feature;
  final bool isHighlighted;

  @override
  Widget build(BuildContext context) {
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 4),
      child: Row(
        children: [
          Icon(Icons.check_circle_outline_rounded,
              size: 18,
              color: isHighlighted ? AppColors.primary : AppColors.secondary),
          const SizedBox(width: AppSpacing.sm),
          Text(feature.displayName,
              style: TextStyle(
                fontWeight: isHighlighted ? FontWeight.w600 : FontWeight.normal,
                color:
                    isHighlighted ? AppColors.onSurface : AppColors.secondary,
              )),
        ],
      ),
    );
  }
}

class _FeatureComparisonTable extends StatelessWidget {
  const _FeatureComparisonTable({required this.currentTier});
  final PlanTier currentTier;

  static const _rows = AppFeature.values;

  @override
  Widget build(BuildContext context) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        const Text('Full Comparison',
            style: TextStyle(fontSize: 18, fontWeight: FontWeight.w700)),
        const SizedBox(height: AppSpacing.md),
        Table(
          columnWidths: const {
            0: FlexColumnWidth(3),
            1: FlexColumnWidth(1),
            2: FlexColumnWidth(1),
            3: FlexColumnWidth(1),
          },
          children: [
            TableRow(
              decoration: BoxDecoration(
                  color: AppColors.surfaceContainerLowest,
                  borderRadius: BorderRadius.circular(8)),
              children: const [
                _TableHeader('Feature'),
                _TableHeader('Free'),
                _TableHeader('Pro'),
                _TableHeader('Ent.'),
              ],
            ),
            for (final feature in _rows)
              TableRow(children: [
                Padding(
                  padding:
                      const EdgeInsets.symmetric(vertical: 10, horizontal: 8),
                  child: Text(feature.displayName,
                      style: const TextStyle(fontSize: 13)),
                ),
                _TableCell(PlanTier.free.includes(feature)),
                _TableCell(PlanTier.pro.includes(feature)),
                _TableCell(PlanTier.enterprise.includes(feature)),
              ]),
          ],
        ),
      ],
    );
  }
}

class _TableHeader extends StatelessWidget {
  const _TableHeader(this.text);
  final String text;

  @override
  Widget build(BuildContext context) {
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 10, horizontal: 8),
      child: Text(text,
          style: const TextStyle(fontWeight: FontWeight.w700, fontSize: 13),
          textAlign: TextAlign.center),
    );
  }
}

class _TableCell extends StatelessWidget {
  const _TableCell(this.included);
  final bool included;

  @override
  Widget build(BuildContext context) {
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 10),
      child: Icon(
        included ? Icons.check_rounded : Icons.remove,
        size: 18,
        color: included
            ? AppColors.primary
            : AppColors.secondary.withValues(alpha: 0.3),
      ),
    );
  }
}
